"""Generate tiny monochrome UI glyphs from a local Windows font; build-time only."""
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parent
TEXT = '正在启动连接网络请稍候热点密码浏览器打开整点了后返回'


def main():
    font = ImageFont.truetype('C:/Windows/Fonts/msyh.ttc', 19)
    lines = ['// Generated by make_ui_glyphs.py; 20x20 monochrome UI glyphs.',
             '#pragma once', '#include <stdint.h>',
             'struct MonoGlyph { uint32_t code; uint8_t bits[60]; };',
             'static const MonoGlyph monoGlyphs[] = {']
    for char in sorted(set(TEXT)):
        image = Image.new('1', (20, 20))
        draw = ImageDraw.Draw(image)
        box = draw.textbbox((0, 0), char, font=font)
        draw.text(((20-(box[2]-box[0]))//2-box[0], (20-(box[3]-box[1]))//2-box[1]), char, font=font, fill=1)
        packed = []
        for y in range(20):
            for b in range(3):
                packed.append(sum((1 << (7-i)) for i in range(8) if b*8+i < 20 and image.getpixel((b*8+i, y))))
        lines.append('  {0x%x, {%s}},' % (ord(char), ','.join('0x%02x' % n for n in packed)))
    lines += ['};', '']
    (ROOT / 'ui_glyphs.h').write_text('\n'.join(lines), encoding='utf-8')


if __name__ == '__main__':
    main()
